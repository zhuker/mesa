static int
make_buffer(const void *src, size_t size, VkBufferUsageFlags usage,
            VkBuffer *out, VkDeviceMemory *out_mem)
{
   VkBufferCreateInfo bci = {
      .sType = VK_STRUCTURE_TYPE_BUFFER_CREATE_INFO,
      .size = size, .usage = usage,
      .sharingMode = VK_SHARING_MODE_EXCLUSIVE };
   CHECK(vkCreateBuffer(dev, &bci, NULL, out));
   VkMemoryRequirements req;
   vkGetBufferMemoryRequirements(dev, *out, &req);
   uint32_t type = pick_memory(pdev, req.memoryTypeBits,
                               VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT |
                               VK_MEMORY_PROPERTY_HOST_COHERENT_BIT);
   if (type == UINT32_MAX) { fprintf(stderr, "no host-visible buffer memory\n"); return 1; }
   VkMemoryAllocateInfo mai = { .sType = VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO,
                                .allocationSize = req.size,
                                .memoryTypeIndex = type };
   CHECK(vkAllocateMemory(dev, &mai, NULL, out_mem));
   CHECK(vkBindBufferMemory(dev, *out, *out_mem, 0));
   void *map = NULL;
   CHECK(vkMapMemory(dev, *out_mem, 0, VK_WHOLE_SIZE, 0, &map));
   memcpy(map, src, size);
   vkUnmapMemory(dev, *out_mem);
   return 0;
}

