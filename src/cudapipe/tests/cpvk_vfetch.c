/*
 * The vertex fetch, tested where the captures cannot reach it.
 *
 * Iteration 27 gathers a vertex's attributes inside the generated vertex
 * shader, from the same routine the standalone cp_vertex_fetch kernel calls,
 * inlined from LLVM bitcode into the shader's own module
 * (CUDAPIPE_FUSED_VFETCH=1). Both forms read kernels/cp_vf_lane.h, so a
 * disagreement between them is a codegen bug and a disagreement with Vulkan
 * is a bug in both. This test pins the second kind, which the replay captures
 * cannot: iteration 4's census found no divisored attribute anywhere in them,
 * and every conversion class they do use appears in one shape only.
 *
 * Four modes, one executable, each drawing white where it agrees with the
 * value Vulkan defines and black where it does not:
 *
 *   formats   one attribute per conversion class -- SFLOAT, UNORM, SNORM,
 *             UINT, SINT, USCALED and FLOAT16 -- at one, two, three and four
 *             components, with a BGRA swizzle, a three-component half format
 *             on a two-byte boundary (the byte-at-a-time path), a 32-bit
 *             format off a sixteen-byte boundary, and every fill_w case. The
 *             shader reads all four components of each, so the zero fill and
 *             the (0,0,0,1) completion are observable. Drawn indexed with a
 *             non-zero firstIndex and a non-zero vertexOffset over a buffer
 *             whose first vertex is poison, so a lost first_vertex is a black
 *             frame rather than a plausible one.
 *
 *   sparse    attributes at locations 0, 3 and 7 with nothing between them and
 *             a shader that reads only location 3. Pins the driver_location =
 *             location rule (the bug that shaded pushconstants' spheres by
 *             their normals) and the fused path's dead-slot elimination, which
 *             gathers only the slots the shader reads: locations 0 and 7 hold
 *             values that fail the test if the shader is handed them.
 *
 *   divisor   a per-vertex attribute and two per-instance ones, four instances
 *             drawn with firstInstance = 2, so the instance attribute's index
 *             is firstInstance + instance and every entry the shader reads is
 *             a different one. This driver's pipeline state maps
 *             VK_VERTEX_INPUT_RATE_INSTANCE to divisor 1 and does not
 *             implement VK_EXT_vertex_attribute_divisor, so a divisor above
 *             one is not reachable through the API; what is exercised here is
 *             the runtime divisor read out of the argument block, which is
 *             the operand the fused build must not fold away.
 *
 *   decline   the divisor draw into the left half of the frame and the sparse
 *             draw into the right half, in one render pass and one submit,
 *             with CUDAPIPE_VFETCH_DECLINE_NTH=1 or 2 forcing one of the two
 *             shaders onto the classic path. Both halves must still be white:
 *             the fetch decision is per launch, and the counter seeding
 *             iteration 26 put on the fetch launch has to follow it.
 *
 * A mode passes when every pixel is exactly white. The vertex shader compares
 * what it was handed against what Vulkan says the format supplies and writes
 * 1.0 or 0.0; the fragment shader paints that, so a single wrong component
 * anywhere darkens the frame. The frame is cleared to black first, so a draw
 * that does not run at all fails too.
 *
 *   cpvk_vfetch <formats|sparse|divisor|decline> [out.ppm]
 *
 * Generated with glslangValidator from the GLSL in the comments beside each
 * SPIR-V array; nothing is read from disk.
 */
